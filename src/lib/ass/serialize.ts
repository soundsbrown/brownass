import type { AssStyle, AssStyleOverrides, Item, Project, TextItem } from "$lib/model/project";
import { formatAssTime } from "$lib/time";
import { styleColor, tagAlpha, tagColor } from "./color";

const STYLE_FORMAT =
  "Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, " +
  "Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, " +
  "Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding";

const EVENT_FORMAT = "Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text";

/** Generates a complete `.ass` file from the project. */
export function serializeAss(project: Project): string {
  const lines = [
    "[Script Info]",
    "; Generated by BrownASS",
    "ScriptType: v4.00+",
    `PlayResX: ${project.playRes.x}`,
    `PlayResY: ${project.playRes.y}`,
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "",
    "[V4+ Styles]",
    `Format: ${STYLE_FORMAT}`,
    ...Object.entries(project.styles).map(([name, style]) => styleLine(name, style)),
    "",
    "[Events]",
    `Format: ${EVENT_FORMAT}`,
    ...sortedForOutput(project.items).flatMap((item) => eventLines(item)),
  ];
  return lines.join("\n") + "\n";
}

/** Events in time order (then layer), which is what other tools expect. */
function sortedForOutput(items: Item[]): Item[] {
  return items.toSorted((a, b) => a.start - b.start || a.layer - b.layer);
}

function eventLines(item: Item): string[] {
  switch (item.type) {
    case "text":
      return [dialogueLine(item)];
  }
}

function styleLine(name: string, s: AssStyle): string {
  const fields = [
    name,
    s.fontName,
    num(s.fontSize),
    styleColor(s.primaryColor),
    styleColor(s.secondaryColor),
    styleColor(s.outlineColor),
    styleColor(s.backColor),
    flag(s.bold),
    flag(s.italic),
    flag(s.underline),
    flag(s.strikeOut),
    num(s.scaleX),
    num(s.scaleY),
    num(s.spacing),
    num(s.angle),
    s.borderStyle,
    num(s.outline),
    num(s.shadow),
    s.alignment,
    s.marginL,
    s.marginR,
    s.marginV,
    s.encoding,
  ];
  return `Style: ${fields.join(",")}`;
}

function dialogueLine(item: TextItem): string {
  const o = item.overrides ?? {};
  const fields = [
    item.layer,
    formatAssTime(item.start),
    formatAssTime(item.end),
    item.styleName,
    "",
    // 0 means "use the style's margin".
    o.marginL ?? 0,
    o.marginR ?? 0,
    o.marginV ?? 0,
    "",
    overrideBlock(o) + escapeText(item.text),
  ];
  return `Dialogue: ${fields.join(",")}`;
}

/** Override tags for everything except margins, which are event fields. */
export function overrideBlock(o: AssStyleOverrides): string {
  const tags: string[] = [];
  if (o.alignment !== undefined) tags.push(`\\an${o.alignment}`);
  if (o.pos) tags.push(`\\pos(${num(o.pos.x)},${num(o.pos.y)})`);
  if (o.fontName !== undefined) tags.push(`\\fn${o.fontName}`);
  if (o.fontSize !== undefined) tags.push(`\\fs${num(o.fontSize)}`);
  if (o.bold !== undefined) tags.push(`\\b${o.bold ? 1 : 0}`);
  if (o.italic !== undefined) tags.push(`\\i${o.italic ? 1 : 0}`);
  if (o.underline !== undefined) tags.push(`\\u${o.underline ? 1 : 0}`);
  if (o.strikeOut !== undefined) tags.push(`\\s${o.strikeOut ? 1 : 0}`);
  if (o.primaryColor) tags.push(`\\1c${tagColor(o.primaryColor)}\\1a${tagAlpha(o.primaryColor)}`);
  if (o.outlineColor) tags.push(`\\3c${tagColor(o.outlineColor)}\\3a${tagAlpha(o.outlineColor)}`);
  if (o.backColor) tags.push(`\\4c${tagColor(o.backColor)}\\4a${tagAlpha(o.backColor)}`);
  if (o.outline !== undefined) tags.push(`\\bord${num(o.outline)}`);
  if (o.shadow !== undefined) tags.push(`\\shad${num(o.shadow)}`);
  if (o.blur !== undefined) tags.push(`\\blur${num(o.blur)}`);
  if (o.fade) tags.push(`\\fad(${Math.round(o.fade.in)},${Math.round(o.fade.out)})`);
  return tags.length ? `{${tags.join("")}}` : "";
}

/**
 * Converts line breaks to `\N`. Everything else, including `{...}` override
 * blocks the user typed, is kept verbatim.
 */
export function escapeText(text: string): string {
  return text.replace(/\r\n|\r|\n/g, "\\N");
}

function flag(b: boolean): string {
  return b ? "-1" : "0";
}

/** Up to three decimals, without trailing zeros. */
function num(n: number): string {
  return String(Number(n.toFixed(3)));
}
