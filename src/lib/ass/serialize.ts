const STYLE_FORMAT =
  "Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, " +
  "Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, " +
  "Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding";

const EVENT_FORMAT = "Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text";

/** Generates a complete `.ass` file from the project. */
export function serializeAss(project: Project): string {
  // Styles are kept in reference pixels; write them in the script's pixels.
  const factor = styleScale(project.playRes);
  const styles = Object.fromEntries(
    Object.entries(project.styles).map(([name, style]) => [name, scaleStyle(style, factor)]),
  );
  const shapeStyles = Object.fromEntries(
    Object.entries(project.shapeStyles).map(([name, s]) => [name, scaleShapeStyle(s, factor)]),
  );
  const context: EventContext = {
    styles,
    shapeStyles,
    playRes: project.playRes,
    factor,
    splitLayers: project.items.some((item) => shadowOf(item, styles, shapeStyles) !== null),
  };
  const lines = [
    "[Script Info]",
    "; Generated by BrownASS",
    "ScriptType: v4.00+",
    `PlayResX: ${project.playRes.x}`,
    `PlayResY: ${project.playRes.y}`,
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "",
    "[V4+ Styles]",
    `Format: ${STYLE_FORMAT}`,
    ...Object.entries(styles).map(([name, style]) => styleLine(name, style)),
    ...Object.entries(shapeStyles).map(([name, style]) => shapeStyleLine(name, style)),
    "",
    "[Events]",
    `Format: ${EVENT_FORMAT}`,
    ...sortedForOutput(project.items).flatMap((item) => eventLines(item, context)),
  ];
  return lines.join("\n") + "\n";
}

/** Events in time order (then layer), which is what other tools expect. */
function sortedForOutput(items: Item[]): Item[] {
  return items.toSorted((a, b) => a.start - b.start || a.layer - b.layer);
}

/** Styles in the script's pixels, and what's needed to place shapes. */
interface EventContext {
  styles: Record<string, AssStyle>;
  shapeStyles: Record<string, ShapeStyle>;
  playRes: { x: number; y: number };
  /** Reference pixels to script pixels. */
  factor: number;
  /**
   * Whether any item casts a shadow. Shadows are separate events, one layer
   * below their item: each item's layer L becomes 2L + 1 and its shadow's 2L,
   * so a shadow lies under every item of its item's layer. Without shadows,
   * layers are written as they are.
   */
  splitLayers: boolean;
}

/** An item's shadow, in script pixels. */
interface Shadow {
  distance: number;
  blur: number;
}

/**
 * The item's shadow, or null if it casts none. A style's blur softens only
 * the shadow, so without a shadow there's nothing to blur.
 */
function shadowOf(
  item: Item,
  styles: Record<string, AssStyle>,
  shapeStyles: Record<string, ShapeStyle>,
): Shadow | null {
  if (item.type === "text") {
    const style = styles[item.styleName];
    const o = item.overrides ?? {};
    const distance = o.shadow ?? style?.shadow ?? 0;
    const color = o.backColor ?? style?.backColor;
    if (distance <= 0 || !color || color.a === 0) return null;
    return { distance, blur: o.blur ?? style?.blur ?? 0 };
  }
  const style = shapeStyles[item.styleName];
  if (!style || style.shadow <= 0 || withOpacity(style.shadowColor, style.opacity).a === 0) {
    return null;
  }
  return { distance: style.shadow, blur: style.blur };
}

/**
 * Tags that turn an event into just its shadow: fill and outline become
 * invisible but still cast it. (libass leaves fully transparent fills out of
 * the shadow, hence nearly transparent.)
 */
function shadowTags(shadow: Shadow): string[] {
  const tags = ["\\1a&HFE&", "\\3a&HFE&", `\\shad${num(shadow.distance)}`];
  if (shadow.blur) tags.push(`\\blur${num(shadow.blur)}`);
  return tags;
}

interface Layers {
  shadow: number;
  main: number;
}

function eventLines(item: Item, context: EventContext): string[] {
  const shadow = shadowOf(item, context.styles, context.shapeStyles);
  const layers: Layers = context.splitLayers
    ? { shadow: item.layer * 2, main: item.layer * 2 + 1 }
    : { shadow: item.layer, main: item.layer };
  switch (item.type) {
    case "text":
      return dialogueLines(item, context.styles[item.styleName], shadow, layers);
    case "shape":
      return shapeLines(item, context, shadow, layers);
  }
}

function styleLine(name: string, s: AssStyle): string {
  const fields = [
    name,
    s.fontName,
    num(s.fontSize),
    styleColor(s.primaryColor),
    styleColor(s.secondaryColor),
    styleColor(s.outlineColor),
    styleColor(s.backColor),
    flag(s.bold),
    flag(s.italic),
    flag(s.underline),
    flag(s.strikeOut),
    num(s.scaleX),
    num(s.scaleY),
    num(s.spacing),
    num(s.angle),
    s.borderStyle,
    num(s.outline),
    // Shadows are separate events (see `shadowTags`).
    0,
    s.alignment,
    s.marginL,
    s.marginR,
    s.marginV,
    s.encoding,
  ];
  return `Style: ${fields.join(",")}`;
}

/**
 * A shape style as an ASS style, so shape events name a valid style. The
 * events set their position and colours themselves.
 */
function shapeStyleLine(name: string, s: ShapeStyle): string {
  const fill = styleColor(withOpacity({ r: 255, g: 255, b: 255, a: 255 }, s.opacity));
  const fields = [
    name,
    "Arial",
    20,
    fill,
    fill,
    styleColor(withOpacity(s.outlineColor, s.opacity)),
    styleColor(withOpacity(s.shadowColor, s.opacity)),
    0,
    0,
    0,
    0,
    100,
    100,
    0,
    0,
    1,
    num(s.outline),
    0,
    s.alignment,
    Math.round(s.marginL),
    Math.round(s.marginR),
    Math.round(s.marginV),
    1,
  ];
  return `Style: ${fields.join(",")}`;
}

/**
 * One drawing event per colour. Each part is placed with `\an7\pos` at its
 * own bounding box, so neither libass's alignment of drawings nor its
 * collision handling can move parts apart. The shadow is one event for the
 * whole shape, so parts never shadow each other.
 */
function shapeLines(
  item: ShapeItem,
  context: EventContext,
  shadow: Shadow | null,
  layers: Layers,
): string[] {
  const style = context.shapeStyles[item.styleName];
  const parts = shapeParts(item.shape).map((p) => ({
    ...p,
    path: scalePath(p.path, context.factor),
  }));
  const box = partsBounds(parts);
  const origin = placeShape(box, style, context.playRes);
  const fade: AssStyleOverrides =
    style.fadeIn || style.fadeOut ? { fade: { in: style.fadeIn, out: style.fadeOut } } : {};
  const line = (layer: number, tags: string[], drawing: string) =>
    "Dialogue: " +
    [
      layer,
      formatAssTime(item.start),
      formatAssTime(item.end),
      item.styleName,
      "",
      0,
      0,
      0,
      "",
      `{${tags.join("")}\\p${DRAWING_LEVEL}}${drawing}`,
    ].join(",");

  // Shadow and outline are of the whole shape: all parts in one drawing, every
  // part turning the same way so that overlapping parts add up instead of
  // cancelling out.
  const silhouette = drawingText(
    parts.flatMap((p) => orientPositive(translatePath(p.path, -box.x, -box.y))),
  );
  const at = overrideTags({ alignment: 7, pos: origin, ...fade });
  const lines: string[] = [];
  if (shadow) lines.push(line(layers.shadow, [...at, ...shadowTags(shadow)], silhouette));
  if (style.outline > 0) {
    // Only the outline shows; the parts are drawn over its inside.
    lines.push(line(layers.main, [...at, "\\1a&HFE&"], silhouette));
  }
  for (const part of parts) {
    const { path, offset } = normalizePath(part.path);
    const tags = overrideTags({
      alignment: 7,
      pos: { x: origin.x + offset.x - box.x, y: origin.y + offset.y - box.y },
      primaryColor: withOpacity(part.color, style.opacity),
      outline: 0,
      ...fade,
    });
    lines.push(line(layers.main, tags, drawingText(path)));
  }
  return lines;
}

/** `c` with its opacity multiplied by `percent`. */
function withOpacity(c: Color, percent: number): Color {
  return { ...c, a: Math.round((c.a * percent) / 100) };
}

/** The caption, preceded by its shadow (the same text, invisible but for its shadow). */
function dialogueLines(
  item: TextItem,
  style: AssStyle | undefined,
  shadow: Shadow | null,
  layers: Layers,
): string[] {
  const o = { ...styleTags(style), ...item.overrides };
  // Shadow and blur are only on the shadow event.
  delete o.shadow;
  delete o.blur;
  const line = (layer: number, tags: string[]) =>
    "Dialogue: " +
    [
      layer,
      formatAssTime(item.start),
      formatAssTime(item.end),
      item.styleName,
      "",
      // 0 means "use the style's margin".
      o.marginL ?? 0,
      o.marginR ?? 0,
      o.marginV ?? 0,
      "",
      (tags.length ? `{${tags.join("")}}` : "") + escapeText(item.text),
    ].join(",");
  const lines = [line(layers.main, overrideTags(o))];
  if (shadow) lines.unshift(line(layers.shadow, [...overrideTags(o), ...shadowTags(shadow)]));
  return lines;
}

/** Style properties ASS styles can't express, applied as tags on each event. */
function styleTags(style: AssStyle | undefined): AssStyleOverrides {
  const tags: AssStyleOverrides = {};
  if (style?.fadeIn || style?.fadeOut) tags.fade = { in: style.fadeIn, out: style.fadeOut };
  return tags;
}

/** Override tags for everything except margins, which are event fields. */
export function overrideBlock(o: AssStyleOverrides): string {
  const tags = overrideTags(o);
  return tags.length ? `{${tags.join("")}}` : "";
}

function overrideTags(o: AssStyleOverrides): string[] {
  const tags: string[] = [];
  if (o.alignment !== undefined) tags.push(`\\an${o.alignment}`);
  if (o.pos) tags.push(`\\pos(${num(o.pos.x)},${num(o.pos.y)})`);
  if (o.fontName !== undefined) tags.push(`\\fn${o.fontName}`);
  if (o.fontSize !== undefined) tags.push(`\\fs${num(o.fontSize)}`);
  if (o.bold !== undefined) tags.push(`\\b${o.bold ? 1 : 0}`);
  if (o.italic !== undefined) tags.push(`\\i${o.italic ? 1 : 0}`);
  if (o.underline !== undefined) tags.push(`\\u${o.underline ? 1 : 0}`);
  if (o.strikeOut !== undefined) tags.push(`\\s${o.strikeOut ? 1 : 0}`);
  if (o.primaryColor) tags.push(`\\1c${tagColor(o.primaryColor)}\\1a${tagAlpha(o.primaryColor)}`);
  if (o.outlineColor) tags.push(`\\3c${tagColor(o.outlineColor)}\\3a${tagAlpha(o.outlineColor)}`);
  if (o.backColor) tags.push(`\\4c${tagColor(o.backColor)}\\4a${tagAlpha(o.backColor)}`);
  if (o.outline !== undefined) tags.push(`\\bord${num(o.outline)}`);
  if (o.shadow !== undefined) tags.push(`\\shad${num(o.shadow)}`);
  if (o.blur !== undefined) tags.push(`\\blur${num(o.blur)}`);
  if (o.fade) tags.push(`\\fad(${Math.round(o.fade.in)},${Math.round(o.fade.out)})`);
  return tags;
}

/**
 * Converts line breaks to `\N`. Everything else, including `{...}` override
 * blocks the user typed, is kept verbatim.
 */
export function escapeText(text: string): string {
  return text.replace(/\r\n|\r|\n/g, "\\N");
}

function flag(b: boolean): string {
  return b ? "-1" : "0";
}

/** Up to three decimals, without trailing zeros. */
function num(n: number): string {
  return String(Number(n.toFixed(3)));
}
